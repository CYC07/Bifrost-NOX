    syn.add(mk_pdf("/Names << /EmbeddedFiles << /Names [(a.exe) 4 0 R] >> >>", "4 0 obj\n<< /Type /EmbeddedFile /Length %d >>\nstream\n" % len(pe) + pe.decode("latin-1") + "\nendstream\nendobj\n"), S, "h.pdf", "pdf", "pdf-embedded-exe")
