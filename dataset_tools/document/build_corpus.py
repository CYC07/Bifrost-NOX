"""Build the document-service evaluation corpora (outside the repo).

Inputs: shallow git clones under ~/FYP/corpora/a6_*/repo (see SOURCES below) and
the local system documents under /usr/share. Output (never inside the repo):

  ~/FYP/corpora/doc_benign/          real benign documents
  ~/FYP/corpora/doc_malicious_real/  real-but-inert public test files with
                                     malicious behaviour (macros, JS, Launch,
                                     DDE, embedded PE, ...)
  ~/FYP/corpora/doc_malicious_synth/ clearly labelled synthetic samples
  ~/FYP/corpora/doc_ambiguous/       real files with /JS or /JavaScript that are
                                     rendering fixtures, not attacks (reported
                                     separately, not part of either gate)

Each directory holds ``manifest.json`` (file -> source/kind/category) and
``SOURCE.txt``. Files are only ever read as bytes; nothing is opened or run.

Run:  python3 -I dataset_tools/document/build_corpus.py
"""

from __future__ import annotations

import hashlib
import io
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.expanduser("~/FYP/corpora")
MAXSIZE = 8 * 1024 * 1024
ZIPPW = b"infected"

SOURCES = {
    "oletools": ("a6_oletools", "https://github.com/decalage2/oletools", "BSD-2-Clause (code); test data per repo"),
    "corkami": ("a6_corkami", "https://github.com/corkami/pocs", "Public domain / CC0 per repo"),
    "pdfjs": ("a6_pdfjs", "https://github.com/mozilla/pdf.js (test/pdfs)", "Apache-2.0"),
    "pypdf": ("a6_pypdf", "https://github.com/py-pdf/pypdf (resources)", "BSD-3-Clause"),
    "formatcorpus": ("a6_formatcorpus", "https://github.com/openpreserve/format-corpus", "CC0 / per-file notes in repo"),
    "python-docx": ("a6_pythondocx", "https://github.com/python-openxml/python-docx", "MIT"),
    "python-pptx": ("a6_pythonpptx", "https://github.com/scanny/python-pptx", "MIT"),
    "xlsxwriter": ("a6_xlsxwriter", "https://github.com/jmcnamara/XlsxWriter", "BSD-2-Clause"),
    "system": (None, "/usr/share, /usr/lib, /opt on the build host", "distribution packages"),
}

PDF_JS = re.compile(rb"/(JS|JavaScript|Launch)(?![A-Za-z0-9])")


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def pdf_has_active(data: bytes) -> bool:
    """True when the raw bytes or any decompressed object carry JS/Launch."""
    if PDF_JS.search(data):
        return True
    try:
        import fitz

        doc = fitz.open(stream=data, filetype="pdf")
        try:
            for x in range(1, doc.xref_length()):
                try:
                    if PDF_JS.search((doc.xref_object(x, compressed=False) or "").encode("latin-1", "ignore")):
                        return True
                except Exception:
                    continue
        finally:
            doc.close()
    except Exception:
        pass
    return False


def walk(src_dir: str):
    for r, ds, fs in os.walk(src_dir):
        ds[:] = [d for d in ds if d != ".git"]
        for f in sorted(fs):
            p = os.path.join(r, f)
            try:
                if os.path.islink(p) or os.path.getsize(p) > MAXSIZE or os.path.getsize(p) < 64:
                    continue
            except OSError:
                continue
            yield p


class Out:
    def __init__(self, name: str):
        self.dir = os.path.join(ROOT, name)
        shutil.rmtree(self.dir, ignore_errors=True)
        os.makedirs(self.dir)
        self.man: dict[str, dict] = {}
        self.seen: set[str] = set()

    def add(self, data: bytes, source: str, origin: str, kind: str, category: str = "") -> bool:
        h = sha(data)
        if h in self.seen:
            return False
        self.seen.add(h)
        ext = os.path.splitext(origin)[1].lower() or ".bin"
        fn = f"{source}_{h[:12]}{ext}"
        with open(os.path.join(self.dir, fn), "wb") as fh:
            fh.write(data)
        self.man[fn] = {"source": source, "origin": origin, "sha256": h, "kind": kind, "category": category}
        return True

    def finish(self, title: str):
        with open(os.path.join(self.dir, "manifest.json"), "w") as fh:
            json.dump(self.man, fh, indent=1, sort_keys=True)
        srcs = sorted({m["source"] for m in self.man.values()})
        with open(os.path.join(self.dir, "SOURCE.txt"), "w") as fh:
            fh.write(f"{title}\nfiles: {len(self.man)}\n\n")
            for s in srcs:
                fh.write(f"[{s}] {SOURCES.get(s, ('', 'synthetic (generated by build_corpus.py)', 'n/a'))[1]}\n")
                fh.write(f"  licence: {SOURCES.get(s, ('', '', 'n/a'))[2]}\n")
            fh.write("\nPer-file sha256 + origin path: see manifest.json\n")
        print(title, len(self.man), {s: sum(1 for m in self.man.values() if m["source"] == s) for s in srcs})


def kind_of(data: bytes, name: str) -> str:
    if data.startswith(b"%PDF"):
        return "pdf"
    if data.startswith(b"PK\x03\x04"):
        e = os.path.splitext(name)[1].lower()
        return {".docx": "docx", ".xlsx": "xlsx", ".pptx": "pptx", ".odt": "odt", ".ods": "odt", ".odp": "odt"}.get(e, "zip")
    return "other"


def has_vba(data: bytes) -> bool:
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as z:
            return any(n.lower().endswith("vbaproject.bin") for n in z.namelist())
    except Exception:
        return False


def collect_benign(benign: Out, ambiguous: Out):
    caps = {"pdfjs": 70, "pypdf": 30, "formatcorpus": 70, "python-docx": 30, "python-pptx": 30, "xlsxwriter": 30, "system": 200}
    exts = (".pdf", ".docx", ".xlsx", ".pptx", ".odt", ".ods", ".odp", ".zip", ".jar", ".epub")
    # priority: files with OpenAction/AcroForm/EmbeddedFile first (the scary-looking benign ones)
    for src, cap in caps.items():
        if src == "system":
            out = subprocess.run(["find", "/usr/share", "/usr/lib", "/opt", "-type", "f", "-size", "-8M"], capture_output=True, text=True).stdout.splitlines()
            paths = [p for p in sorted(out) if os.path.splitext(p)[1].lower() in exts
                     and not any(k in p.lower() for k in ("yara", "malware", "eicar", "/ai_firewall/"))]
        else:
            paths = [p for p in walk(os.path.join(ROOT, SOURCES[src][0], "repo")) if os.path.splitext(p)[1].lower() in exts]
            if src == "formatcorpus":
                # exclude intentionally corrupt/edge-case sets; keep government/real-world-ish PDFs and office
                paths = [p for p in paths if "pdfCabinetOfHorrors" not in p and "jhove-errors" not in p and "pdf-handbuilt" not in p]
        scored = []
        for p in paths:
            try:
                data = open(p, "rb").read()
            except OSError:
                continue
            if data.startswith(b"%PDF"):
                if pdf_has_active(data):
                    ambiguous.add(data, src, p, "pdf", "pdf-js-fixture")
                    continue
                pri = 0 if (b"/OpenAction" in data or b"/AcroForm" in data or b"/EmbeddedFile" in data) else 1
            elif data.startswith(b"PK\x03\x04"):
                if has_vba(data):
                    continue
                pri = 1
            else:
                continue
            scored.append((pri, p, data))
        scored.sort(key=lambda t: (t[0], t[1]))
        # take scary-looking ones first but keep a spread of ordinary files
        n = 0
        picks = [t for t in scored if t[0] == 0][: cap // 2] + [t for t in scored if t[0] == 1]
        for pri, p, data in picks:
            if n >= cap:
                break
            if benign.add(data, src, p, kind_of(data, p), "openaction/form/attachment" if pri == 0 else "plain"):
                n += 1


def collect_system_pdfs(out: Out):
    """Every PDF shipped on the host (no filtering): a fixed, reproducible benign section."""
    found = subprocess.run(["find", "/usr/share", "/usr/lib", "/opt", "-type", "f", "-iname", "*.pdf", "-size", "-30M"],
                           capture_output=True, text=True).stdout.splitlines()
    for p in sorted(found):
        if any(k in p.lower() for k in ("yara", "malware", "eicar", "/ai_firewall/")):
            continue
        try:
            data = open(p, "rb").read()
        except OSError:
            continue
        if data.startswith(b"%PDF"):
            out.add(data, "system", p, "pdf", "system-pdf")


def collect_real_malicious(mal: Out):
    ole = os.path.join(ROOT, "a6_oletools", "repo", "tests", "test-data")
    for p in walk(ole):
        e = os.path.splitext(p)[1].lower()
        data = open(p, "rb").read()
        rel = os.path.relpath(p, ole)
        if e == ".zip" and "infected" or e == ".zip":
            try:
                with zipfile.ZipFile(io.BytesIO(data)) as z:
                    for zi in z.infolist():
                        inner = z.read(zi, pwd=ZIPPW)
                        cat = "ooxml-dde" if "dde" in zi.filename.lower() else "ole/rtf-exploit"
                        mal.add(inner, "oletools", rel + "!" + zi.filename, kind_of(inner, zi.filename), cat + "-zipped")
            except Exception:
                pass
            continue
        if data.startswith(b"PK\x03\x04"):
            if has_vba(data):
                mal.add(data, "oletools", rel, kind_of(data, p), "ooxml-macro")
            elif rel.startswith("msodde") and "harmless" not in rel and e in (".docx", ".xlsx", ".xlsb"):
                mal.add(data, "oletools", rel, kind_of(data, p), "ooxml-dde")
            elif "external_link" in rel and e in (".docx", ".xlsx", ".pptx"):
                mal.add(data, "oletools", rel, kind_of(data, p), "ooxml-external-link")
        elif data.startswith(b"\xd0\xcf\x11\xe0") and "harmless" not in rel and "encrypted" not in rel and "basic" not in rel:
            mal.add(data, "oletools", rel, "ole", "ole-office")
        elif e == ".rtf" and "RTF-Spec" not in rel:
            mal.add(data, "oletools", rel, "rtf", "rtf-exploit")
    ck = os.path.join(ROOT, "a6_corkami", "repo")
    for p in walk(ck):
        if not p.lower().endswith(".pdf"):
            continue
        n = os.path.basename(p).lower()
        data = open(p, "rb").read()
        if re.match(r"(js-|javascript|launch|formevent_js|globalvariables|pdf_zip_pe|pdf-pe1)", n):
            mal.add(data, "corkami", os.path.relpath(p, ck), "pdf", "pdf-js/launch/embedded-pe")


def mk_pdf(extra_catalog: str, objs: str = "", pages: int = 1) -> bytes:
    body = f"%PDF-1.7\n1 0 obj\n<< /Type /Catalog /Pages 2 0 R {extra_catalog} >>\nendobj\n"
    body += "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n"
    body += "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 200] >>\nendobj\n" + objs
    body += "trailer\n<< /Root 1 0 R /Size 99 >>\n%%EOF\n"
    return body.encode("latin-1")


