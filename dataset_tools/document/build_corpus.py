    syn.add(b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1" + b"\x00" * 100 + b"Equation Native" + b"\x00" * 50 + b"Microsoft Equation 3.0", S, "cve2017_11882.doc", "ole", "ole-equation-editor")
