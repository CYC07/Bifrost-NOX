def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_source(d: str, licence: str, usage: str, entries: list[tuple[str, str]]) -> None:
    with open(os.path.join(d, "SOURCE.txt"), "w", encoding="utf-8") as f:
        f.write(f"fetched: {time.strftime('%Y-%m-%d')} by dataset_tools/sensitive/fetch.py\n")
        f.write(f"licence: {licence}\nusage: {usage}\n")
        for url, digest in entries:
            f.write(f"file: {url}\nsha256: {digest}\n")


def fetch_hf(root: str, name: str) -> None:
    from huggingface_hub import hf_hub_download
    licence, usage, files = HF_SOURCES[name]
    d = os.path.join(root, f"sens_{name}")
    os.makedirs(d, exist_ok=True)
    entries = []
    for item in files:
        repo, fn = item[0], item[1]
        rev = item[2] if len(item) > 2 else None
        p = hf_hub_download(repo_id=repo, filename=fn, repo_type="dataset", revision=rev, local_dir=os.path.join(d, "raw", repo.replace("/", "__")))
        entries.append((f"https://huggingface.co/datasets/{repo}/resolve/{rev or 'main'}/{fn}", sha256(p)))
        print("  ", repo, fn, os.path.getsize(p))
    write_source(d, licence, usage, entries)


def fetch_site_policy(root: str) -> None:
    d = os.path.join(root, "sens_githubpolicy")
    if os.path.isdir(os.path.join(d, "repo", ".git")):
        return
    os.makedirs(d, exist_ok=True)
    subprocess.run(["git", "clone", "--depth", "1", "--single-branch", "https://github.com/github/site-policy", os.path.join(d, "repo")], check=True)
    head = subprocess.run(["git", "-C", os.path.join(d, "repo"), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    write_source(d, "CC0-1.0 (github/site-policy: GitHub Terms of Service, privacy statement, policies)",
                 "BENIGN public-facing legal: GitHub's own ToS / privacy documents",
                 [("https://github.com/github/site-policy", f"git commit {head}")])


def fetch_local_docs(root: str) -> None:
    """Licences, man pages and package READMEs already installed on this machine (system files, copied as text)."""
    d = os.path.join(root, "sens_localdocs")
    if os.path.isdir(os.path.join(d, "licenses")):
        return
    os.makedirs(os.path.join(d, "licenses"), exist_ok=True)
    os.makedirs(os.path.join(d, "man"), exist_ok=True)
    os.makedirs(os.path.join(d, "readme"), exist_ok=True)
    n = 0
    for base, _dirs, names in os.walk("/usr/share/licenses"):
        for fn in names:
            if fn.upper().startswith(("COPYING", "LICENSE", "LICENCE")) or fn in ("GPL-2.0", "GPL-3.0", "MIT", "Apache-2.0", "BSD"):
                src = os.path.join(base, fn)
                try:
                    if os.path.getsize(src) < 200 or os.path.getsize(src) > 200_000:
                        continue
                    shutil.copyfile(src, os.path.join(d, "licenses", f"{n:05d}_{fn}"))
                    n += 1
                except OSError:
                    continue
    # man pages: rendered with groff (a system tool) from the installed roff sources
    mans = []
    for base, _dirs, names in os.walk("/usr/share/man/man1"):
        mans.extend(os.path.join(base, x) for x in names if x.endswith(".gz"))
    mans.sort()
    for i, src in enumerate(mans[:: max(1, len(mans) // 400)]):
        try:
            out = subprocess.run(f"gzip -dc '{src}' | groff -man -Tutf8 -P-c 2>/dev/null", shell=True, capture_output=True, text=True, timeout=20).stdout
        except Exception:  # noqa: BLE001
            continue
        if len(out) > 300:
            with open(os.path.join(d, "man", f"{i:04d}_{os.path.basename(src)[:-3]}.txt"), "w", encoding="utf-8") as f:
                f.write(out)
    k = 0
    for base, _dirs, names in os.walk("/usr/share/doc"):
        for fn in names:
            if fn.upper().startswith("README") and not fn.endswith((".gz", ".png", ".html")):
                src = os.path.join(base, fn)
                try:
                    if 400 < os.path.getsize(src) < 100_000:
                        shutil.copyfile(src, os.path.join(d, "readme", f"{k:05d}_{fn}"))
                        k += 1
                except OSError:
                    continue
    write_source(d, "mixed OSS licences and documentation shipped with installed Arch packages",
                 "BENIGN public legal (open licence texts) and product documentation (man pages, READMEs)",
                 [("local: /usr/share/licenses, /usr/share/man/man1 (rendered via groff), /usr/share/doc/*/README*", f"{n} licences, {len(os.listdir(os.path.join(d, 'man')))} man pages, {k} readmes")])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=ROOT_DEFAULT)
    ap.add_argument("--only", default="")
    a = ap.parse_args()
    root = os.path.expanduser(a.root)
    only = {s for s in a.only.split(",") if s}
    for name in HF_SOURCES:
        if only and name not in only:
            continue
        print("==", name)
        try:
            fetch_hf(root, name)
        except Exception as exc:  # noqa: BLE001 — report and continue
            print("   FAILED:", type(exc).__name__, str(exc)[:200], file=sys.stderr)
    if not only or "githubpolicy" in only:
        print("== githubpolicy")
        try:
            fetch_site_policy(root)
        except Exception as exc:  # noqa: BLE001
            print("   FAILED:", exc, file=sys.stderr)
    if not only or "localdocs" in only:
        print("== localdocs")
        fetch_local_docs(root)


if __name__ == "__main__":
    main()
