def chat_bodies(question: str, assistant_reply: str | None = None) -> dict[str, str]:
    """The request bodies a client would send for one question (plain text + chat-JSON variants)."""
    def body(msgs, model="gpt-4o"):
        return json.dumps({"model": model, "messages": [{"role": r, "content": c} for r, c in msgs]})
    out = {"plain": question, "chat_user": body([("user", question)])}
    for i, sp in enumerate(SYSTEM_PROMPTS):
        out[f"chat_sys{i}"] = body([("system", sp), ("user", question)])
    out["chat_multi"] = body([("system", SYSTEM_PROMPTS[0]), ("user", question), ("assistant", assistant_reply or GENERIC_REPLY), ("user", FOLLOW_UP)])
    return out


def rid(set_: str, text: str) -> str:
    return hashlib.sha1((set_ + "\0" + text).encode("utf-8", "ignore")).hexdigest()[:14]


def rec(set_: str, text: str) -> dict:
    i = rid(set_, text)
    return {"id": i, "set": set_, "label": "neg", "confusable": True, "synthetic": set_ == "chatq_template", "marked": False,
            "split": "dev" if int(i, 16) % 2 == 0 else "test", "text": text}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.expanduser("~/FYP/corpora"))
    ap.add_argument("--out", default=os.path.expanduser("~/FYP/corpora/sens_eval"))
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    recs: list[dict] = []
    seen: set[str] = set()

    def add(set_, texts, n):
        pool = [t.strip() for t in texts if t.strip() and t.strip() not in seen]
        rng.shuffle(pool)
        for t in pool[:n]:
            seen.add(t)
            recs.append(rec(set_, t))
        print(f"  {set_:18s} {min(n, len(pool))}")

    templ = [q for qs in TEMPLATE_QUESTIONS.values() for q in qs]
    add("chatq_template", templ, len(templ))
    add("chatq_statement", TEMPLATE_STATEMENTS, len(TEMPLATE_STATEMENTS))
    fin = json.load(open(glob.glob(os.path.join(a.root, "sens_chat_finance/raw/*/Cleaned_date.json"))[0], encoding="utf-8"))
    add("chatq_finance", [d["instruction"] for d in fin if not d.get("input") and 40 <= len(d["instruction"]) <= 260
                          and FIN_KW.search(d["instruction"]) and d["instruction"].rstrip().endswith("?")], 40)
    dolly = [json.loads(l) for l in open(glob.glob(os.path.join(a.root, "sens_chat_dolly/raw/*/databricks-dolly-15k.jsonl"))[0], encoding="utf-8")]
    add("chatq_dolly", [d["instruction"] for d in dolly if d["category"] in ("open_qa", "general_qa") and not d["context"]
                        and 30 <= len(d["instruction"]) <= 260 and DOLLY_KW.search(d["instruction"])], 40)
    mq = pl.read_csv(glob.glob(os.path.join(a.root, "sens_med_public/raw/*MedQuad*/medDataset_processed.csv"))[0], ignore_errors=True)
    add("chatq_medquad", [str(q).strip() for q in mq["Question"].drop_nulls().to_list() if 25 <= len(str(q)) <= 200], 30)
    base_q = [r["text"] for r in recs if r["set"] != "chatq_statement"]
    multi = [f"{q}\n{GENERIC_REPLY}\n{FOLLOW_UP}" for q in rng.sample(base_q, 60)]
    add("chatq_multiturn", multi, 60)
    random.Random(a.seed).shuffle(recs)
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "chat_eval.jsonl"), "w", encoding="utf-8") as f:
        for r in recs:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("total", len(recs))


if __name__ == "__main__":
    main()
