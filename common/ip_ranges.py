"""Membership test against Microsoft's published IP ranges (config/microsoft_ip_ranges.json).

Used to verify that a connection whose SNI/Host claims a trusted Microsoft domain really goes to
Microsoft address space. Generated by scripts/update_microsoft_ranges.py; hot-reloaded on mtime.
A missing or corrupt file means "nothing is contained" (callers then fail closed to normal
inspection). Entries that would match everything (/0) are ignored.
"""
from __future__ import annotations

import bisect
import ipaddress
import json
import logging
import os
import threading

logger = logging.getLogger("ip_ranges")

_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "config", "microsoft_ip_ranges.json"))
_lock = threading.Lock()
# (mtime, {4: (starts, ends), 6: (starts, ends)}) with merged, sorted, non-overlapping intervals
_cache: tuple[float | None, dict[int, tuple[list[int], list[int]]]] | None = None


def _reset_cache() -> None:
    global _cache
    with _lock:
        _cache = None


def _build(entries) -> dict[int, tuple[list[int], list[int]]]:
    raw: dict[int, list[tuple[int, int]]] = {4: [], 6: []}
    for e in entries if isinstance(entries, list) else []:
        if not isinstance(e, str):
            continue
        try:
            net = ipaddress.ip_network(e.strip(), strict=False)
        except ValueError:
            continue
        if net.prefixlen == 0:
            continue
        raw[net.version].append((int(net.network_address), int(net.broadcast_address)))
    out = {}
    for ver, spans in raw.items():
        merged: list[list[int]] = []
        for s, e in sorted(spans):
            if merged and s <= merged[-1][1] + 1:
                merged[-1][1] = max(merged[-1][1], e)
            else:
                merged.append([s, e])
        out[ver] = ([m[0] for m in merged], [m[1] for m in merged])
    return out


def _table() -> dict[int, tuple[list[int], list[int]]]:
    global _cache
    try:
        mtime = os.stat(_PATH).st_mtime
    except OSError:
        mtime = None
    with _lock:
        if _cache is not None and _cache[0] == mtime:
            return _cache[1]
        table = {4: ([], []), 6: ([], [])}
        if mtime is not None:
            try:
                with open(_PATH) as f:
                    data = json.load(f)
                table = _build(data.get("ranges") if isinstance(data, dict) else None)
            except Exception as exc:
                logger.error(f"Failed to load Microsoft IP ranges: {exc}")
        _cache = (mtime, table)
        return table


def loaded() -> bool:
    t = _table()
    return bool(t[4][0] or t[6][0])


def contains(ip) -> bool:
    if not isinstance(ip, str):
        return False
    try:
        addr = ipaddress.ip_address(ip.strip())
    except ValueError:
        return False
    starts, ends = _table()[addr.version]
    i = bisect.bisect_right(starts, int(addr)) - 1
    return i >= 0 and int(addr) <= ends[i]
